import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { demoBoard } from '../src/lib/types.ts';
const board = demoBoard();
const description = Array.from({ length: 8 }, (_, i) => `Paragraph ${i + 1}: This description should expand completely, with every sentence and line break preserved.`).join('\n\n') + '\n\nTHE FINAL SENTENCE.';
board.nodes[0].data.description = description;
board.nodes[0].selected = true;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
await page.addInitScript(board => { if (!localStorage.getItem('idea-garden-boards')) localStorage.setItem('idea-garden-boards', JSON.stringify([board])); }, board);
await page.route('**/api/generate', route => route.fulfill({ json: { verdict: { originality: 4, feasibility: 4, impact: 4, reason: 'Card test.', keywords: [] } } }));
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:4340'); await page.locator('.idea-node').first().waitFor();
  const cards = page.locator('.idea-node');
  const first = cards.filter({ has: page.getByRole('heading', { name: board.nodes[0].data.title, exact: true }) });
  await expect(page.locator('.idea-description')).toHaveCount(0);
  const collapsedHeight = (await first.boundingBox()).height;
  await first.getByRole('heading').click();
  await expect(first.locator('.idea-description')).toHaveText(description);
  await expect(page.locator('.idea-description')).toHaveCount(1);
  assert.equal(await page.getByLabel('The idea', { exact: true }).inputValue(), description);
  const metrics = await first.locator('.idea-description').evaluate(el => ({ scroll: el.scrollHeight, height: el.clientHeight, clamp: getComputedStyle(el).webkitLineClamp, overflow: getComputedStyle(el).overflowY }));
  assert(metrics.scroll <= metrics.height + 1); assert.equal(metrics.clamp, 'none'); assert.equal(metrics.overflow, 'visible');
  assert((await first.boundingBox()).height > collapsedHeight + 150);
  await page.getByRole('heading', { name: board.nodes[1].data.title, exact: true }).click();
  await expect(first.locator('.idea-description')).toHaveCount(0);
  await expect(page.locator('.idea-description')).toHaveCount(1);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Idea View', { exact: true }).selectOption('modal');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('dialog', { name: 'Settings', exact: true }).waitFor({ state: 'hidden' });
  await first.getByRole('heading').click();
  const modal = page.getByRole('dialog', { name: 'Idea details', exact: true }); await modal.waitFor();
  assert.equal(await modal.getByLabel('The idea', { exact: true }).inputValue(), description);
  await expect(first.locator('.idea-description')).toHaveText(description);
  await modal.getByRole('button', { name: 'Close idea details', exact: true }).click(); await modal.waitFor({ state: 'hidden' });
  await expect(first.locator('.idea-description')).toHaveCount(1);
  await page.reload(); await cards.first().waitFor();
  await expect(page.locator('.idea-description')).toHaveCount(0);
  await first.getByRole('button', { name: `Evaluate idea: ${board.nodes[0].data.title}`, exact: true }).click();
  await expect(first.locator('.node-score')).toHaveText('12 / 15');
  await expect(page.locator('.idea-description')).toHaveCount(0);
  await expect(first).toHaveClass(/score-colored/);
  assert.deepEqual(errors, []);
  console.log('Card expansion checks passed: collapsed startup/reload, full unclamped multiline description on click, previous card collapse, matching sidebar/modal content, and quick actions staying collapsed.');
} finally { await browser.close(); }
