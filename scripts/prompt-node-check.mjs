import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { seedExample } from './test-fixtures.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
await seedExample(page);
await page.addInitScript(() => {
  if (!localStorage.getItem('idea-garden-settings')) localStorage.setItem('idea-garden-settings', JSON.stringify({ autoEvaluate: true, roleModels: { prompt: 'ollama:build-model' } }));
});
const markdown = '# Build a useful tool\n\nYou are an experienced engineer. Build **a focused MVP**.\n\n## Requirements\n\n- Persist ideas locally\n- Support keyboard navigation\n\n## Implementation\n\n```ts\nconst ready = true;\n```\n\n## Acceptance criteria\n\n1. Run the tests\n2. Verify saved data\n\n<script>window.promptInjected = true</script><img src="x" onerror="window.promptInjected = true"><a href="javascript:alert(1)">unsafe</a>\n';
const calls = [], errors = [];
let release, fail = false;
const gate = new Promise(resolve => release = resolve);
page.on('pageerror', e => errors.push(e.message));
await page.route('**/api/models', route => route.fulfill({ json: { models: [] } }));
await page.route('**/api/generate', async route => {
  const body = route.request().postDataJSON(); calls.push(body);
  assert.equal(body.role, 'prompt');
  await gate;
  return route.fulfill(fail ? { status: 500, json: { error: 'Prompt provider unavailable.' } } : { json: { markdown } });
});
const title = 'Tiny rituals, real momentum';
const source = page.locator('.idea-node').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
const trigger = source.getByRole('button', { name: `Generate Prompt: ${title}`, exact: true });
const prompt = page.locator('.prompt-node');
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:4340');
  await source.waitFor();
  await trigger.hover();
  await expect.poll(() => source.locator('[data-tip="Generate Prompt"]').evaluate(el => getComputedStyle(el, '::before').opacity)).toBe('1');
  await trigger.click();
  await expect(source.getByRole('status')).toHaveText('Generating prompt…');
  await expect(trigger).toBeDisabled();
  await expect(prompt).toHaveCount(0);
  release();
  await expect(prompt).toHaveCount(1);
  await expect(trigger).toBeEnabled();
  assert.equal(calls[0].provider, 'ollama'); assert.equal(calls[0].model, 'build-model');
  const input = JSON.parse(calls[0].context);
  assert.equal(input.idea.title, title); assert.equal(input.parentIdeas.length, 2);
  assert.equal(calls.length, 1); // Prompt nodes are never auto-evaluated.
  await expect(page.locator('.idea-node')).toHaveCount(4);
  await expect(prompt.locator('.prompt-markdown')).toHaveCount(0);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('idea-garden-boards'))[0]);
  const saved = stored.nodes.find(n => n.type === 'prompt');
  assert.equal(saved.data.markdown, markdown);
  assert(stored.edges.some(e => e.source === 'demo-3' && e.target === saved.id));
  await prompt.getByRole('button', { name: /^Read prompt:/ }).click();
  await expect(prompt.getByRole('heading', { name: 'Build a useful tool', exact: true })).toBeVisible();
  await expect(prompt.locator('pre code')).toHaveText('const ready = true;\n');
  assert.equal(await prompt.locator('script, img, [onerror], [href^="javascript:"]').count(), 0);
  assert.equal(await page.evaluate(() => window.promptInjected), undefined);
  await prompt.locator('.prompt-markdown strong').click();
  await expect(prompt.locator('.prompt-markdown')).toBeVisible();
  await prompt.getByRole('button', { name: 'Copy Markdown', exact: true }).click();
  assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n'), markdown);
  await expect(prompt.getByRole('button', { name: /^Read prompt:/ })).toHaveAttribute('aria-expanded', 'true');
  const downloadWait = page.waitForEvent('download');
  await prompt.getByRole('button', { name: 'Download Markdown', exact: true }).click();
  const download = await downloadWait;
  assert(download.suggestedFilename().endsWith('-prompt.md'));
  let downloaded = ''; for await (const chunk of await download.createReadStream()) downloaded += chunk.toString();
  assert.equal(downloaded, markdown);
  await page.screenshot({ path: 'screenshots/prompt-node.png', fullPage: true });
  await page.reload(); await prompt.waitFor();
  await expect(prompt.locator('.prompt-markdown')).toHaveCount(0);
  await prompt.getByRole('button', { name: /^Read prompt:/ }).focus();
  await prompt.getByRole('button', { name: /^Read prompt:/ }).press('Enter');
  await expect(prompt.locator('.prompt-markdown')).toBeVisible();
  const backupWait = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export workspace', exact: true }).click();
  const backup = await backupWait; let json = ''; for await (const chunk of await backup.createReadStream()) json += chunk.toString();
  await page.locator('input[type="file"]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(json) });
  await page.getByText('Boards imported successfully.', { exact: true }).waitFor();
  await expect(prompt).toHaveCount(1);
  fail = true;
  await trigger.click();
  await page.getByText('Prompt provider unavailable.', { exact: true }).waitFor();
  await expect(prompt).toHaveCount(1);
  await expect(source.getByRole('status')).not.toHaveClass(/working/);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Models', exact: true }).click();
  await expect(page.getByRole('button', { name: 'prompt model', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Idea View', { exact: true }).selectOption('modal');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await prompt.getByRole('button', { name: /^Read prompt:/ }).click();
  await expect(prompt.locator('.prompt-markdown')).toBeVisible();
  await expect(page.getByRole('dialog', { name: 'Idea details', exact: true })).not.toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await prompt.getByRole('button', { name: /^Delete prompt:/ }).click();
  await expect(prompt).toHaveCount(0);
  await expect(page.locator('.idea-node')).toHaveCount(4);
  assert.deepEqual(errors, []);
  console.log('Prompt nodes passed: tooltip/progress, model override/context, connected document node, safe formatted Markdown, keyboard expansion, copy/download, persistence/import, no auto-evaluation, failures, Modal mode, and mobile.');
} finally { await browser.close(); }
