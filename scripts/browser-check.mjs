import { seedExample } from './test-fixtures.mjs';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
await seedExample(page);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const base = process.env.APP_URL || 'http://127.0.0.1:4340';
  const denied = await page.request.post(`${base}/api/generate`, { data: {} });
  assert.equal(denied.status(), 403);
  const invalid = await page.request.post(`${base}/api/generate`, { headers: { Origin: base }, data: { provider: 'unknown', role: 'seed' } });
  assert.equal(invalid.status(), 400);
  await page.goto(base);
  await page.locator('.idea-node').first().waitFor();
  assert.equal(await page.locator('.idea-node').count(), 4);
  await mkdir('screenshots', { recursive: true });
  await page.screenshot({ path: 'screenshots/garden.png', fullPage: true });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Choose theme', exact: true }).click();
  const themeDialog = page.getByRole('dialog', { name: 'Appearance', exact: true });
  assert.equal(await themeDialog.locator('.theme-choice').count(), 36);
  assert.equal(await themeDialog.getByRole('button', { name: 'Use abyss theme', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await themeDialog.locator('.theme-choice').first().locator('i').count(), 3);
  const swatches = await themeDialog.locator('.theme-choice').first().locator('i').evaluateAll(elements => elements.map(el => getComputedStyle(el).backgroundColor));
  assert.equal(new Set(swatches).size, 3);
  await themeDialog.getByRole('button', { name: 'Use light theme', exact: true }).press('Enter');
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.keyboard.press('Escape');
  await themeDialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Choose theme', exact: true }).click();
  await themeDialog.getByRole('button', { name: 'Use omp theme', exact: true }).click();
  await page.screenshot({ path: 'screenshots/theme-picker.png', fullPage: true });
  await themeDialog.getByRole('button', { name: 'Close themes', exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'omp');
  await page.getByRole('tab', { name: 'Connections', exact: true }).click();
  assert.equal(await page.getByPlaceholder('Enter API key').count(), 3);
  await page.getByPlaceholder('Enter API key').first().fill('test-secret-not-persisted');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  assert(!await page.evaluate(() => localStorage.getItem('idea-garden-settings').includes('test-secret-not-persisted')));
  await page.getByRole('button', { name: 'New workspace', exact: true }).click();
  await page.getByLabel('Workspace name').fill('Browser validation');
  await page.getByLabel('What are we working toward?').fill('Build tools that help neighbours.');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByLabel('Your seed idea').fill('A tiny neighbourhood library');
  await page.getByRole('button', { name: 'Add seed idea', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).waitFor();
  assert.equal(await page.locator('.idea-node').count(), 1);
  await page.getByRole('button', { name: 'Save idea', exact: true }).click();
  // Stub only the app boundary: never make paid provider calls during browser validation.
  await page.route('**/api/generate', async route => {
    const body = route.request().postDataJSON();
    const result = body.role === 'branch' ? { ideas: [1,2,3].map(i => ({ title: `Branch ${i}`, description: 'A concrete new direction.' })) } : body.role === 'cross' ? { ideas: [{ title: 'Combined direction', description: 'A combination of both parents.' }] } : body.role === 'judge' ? { verdict: { originality: 4, feasibility: 5, impact: 4, reason: 'Test verdict.', keywords: ['local','useful'] } } : { summary: 'Board summary from test.' };
    await route.fulfill({ json: result });
  });
  await page.getByRole('button', { name: 'Branch into 3 ideas', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.idea-node').length === 4);
  await page.getByLabel('Idea to combine with').selectOption({ label: 'A tiny neighbourhood library' });
  await page.getByRole('button', { name: 'Combine ideas', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.idea-node').length === 5);
  await page.getByRole('button', { name: 'Evaluate this idea', exact: true }).click();
  await page.getByText('Test verdict.', { exact: true }).waitFor();
  const exportPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export workspace', exact: true }).click();
  const backup = await exportPromise;
  const { readFile } = await import('node:fs/promises');
  const text = await readFile(await backup.path(), 'utf8');
  assert(!text.includes('test-secret-not-persisted'));
  const exported = JSON.parse(text);
  assert.equal(exported.boards.at(-1).nodes.length, 5);
  assert.equal(exported.boards.at(-1).edges.length, 5);
  await page.reload();
  await page.locator('.idea-node').first().waitFor();
  assert.equal(await page.locator('.idea-node').count(), 5);
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'omp');
  await page.getByRole('heading', { name: 'Combined direction', exact: true }).click();
  await page.getByRole('button', { name: 'Delete idea: A tiny neighbourhood library', exact: true }).click();
  assert.equal(await page.locator('.idea-node').count(), 4);
  assert.equal(await page.getByLabel('Title', { exact: true }).inputValue(), 'Combined direction');
  await page.waitForFunction(() => {
    const boards = JSON.parse(localStorage.getItem('idea-garden-boards'));
    return boards.at(-1).nodes.length === 4 && boards.at(-1).edges.length === 1;
  });
  await page.getByRole('button', { name: 'Delete idea: Combined direction', exact: true }).click();
  assert.equal(await page.locator('.idea-node').count(), 3);
  assert.equal(await page.getByLabel('Title', { exact: true }).count(), 0);
  await page.reload();
  await page.locator('.idea-node').first().waitFor();
  assert.equal(await page.locator('.idea-node').count(), 3);
  assert.equal(await page.locator('.svelte-flow__edge').count(), 0);
  await page.getByRole('button', { name: 'Import boards', exact: true }).click({ trial: true });
  await page.locator('input[type=file]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(text) });
  await page.waitForFunction(() => document.querySelectorAll('.board-link').length === 4);
  await page.getByRole('button', { name: 'Toggle idea inspector', exact: true }).click();
  await page.screenshot({ path: 'screenshots/plum.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Choose theme', exact: true }).click();
  await themeDialog.getByRole('button', { name: 'Use dracula theme', exact: true }).click();
  await page.screenshot({ path: 'screenshots/theme-picker-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await themeDialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.screenshot({ path: 'screenshots/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: graph, themes, manual seeds, branching, combining, jury, node deletion and connection cleanup, persistence, backup/import, key exclusion, mobile layout.');
} finally { await browser.close(); }
