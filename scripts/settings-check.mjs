  assert.equal(await settings.getByPlaceholder('Enter API key').first().inputValue(), 'test-key-in-memory');
  await done();
  assert.equal(await page.locator('.inspector').count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Toggle idea inspector', exact: true }).count(), 0);
