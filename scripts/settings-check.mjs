  const themes = page.getByRole('dialog', { name: 'Appearance', exact: true });
  await themes.getByRole('button', { name: 'Use coffee theme', exact: true }).click();
  await page.keyboard.press('Escape'); await themes.waitFor({ state: 'hidden' });
  assert.equal(await settings.isVisible(), true);
  await settings.getByLabel('Idea View', { exact: true }).selectOption('modal');
  await mkdir('screenshots', { recursive: true });
  await page.screenshot({ path: 'screenshots/settings-tabs.png', fullPage: true });
