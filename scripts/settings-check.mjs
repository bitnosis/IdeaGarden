const idea = page.getByRole('dialog', { name: 'Idea details', exact: true });
async function openSettings() { await page.getByRole('button', { name: 'Settings', exact: true }).click(); await settings.waitFor(); }
async function done() { await settings.getByRole('button', { name: 'Done', exact: true }).click(); await settings.waitFor({ state: 'hidden' }); }
