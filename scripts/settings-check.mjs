  assert.equal(await page.locator('.inspector').count(), 1);
  assert.deepEqual(errors, []);
  console.log('Settings checks passed: tabs, theme picker, connection state, idea view persistence, modal editing/star/jury/branch/combine/export/delete, search, sidebar toggle, mobile layout.');
