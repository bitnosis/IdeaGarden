import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1450, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const base = process.env.APP_URL || 'http://127.0.0.1:4340';
async function create(name, first = false) {
  await page.getByRole('button', { name: first ? 'Create your first workspace' : 'New workspace', exact: true }).click();
  await page.getByLabel('Workspace name', { exact: true }).fill(name);
  await page.getByLabel('What are we working toward?', { exact: true }).fill('A goal kept behind the scenes.');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.locator('.graph-area').waitFor();
}
const warning = page.getByRole('dialog', { name: 'Delete workspace', exact: true });
try {
  await page.goto(base);
  await page.waitForFunction(() => localStorage.getItem('idea-garden-boards') === '[]');
  assert.equal(await page.locator('.board-link').count(), 0);
  assert.equal(await page.locator('.idea-node').count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Toggle idea inspector', exact: true }).count(), 0);
  await mkdir('screenshots', { recursive: true });
  await page.screenshot({ path: 'screenshots/empty-workspace.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1450, height: 1000 });
  await create('First workspace', true);
  assert.equal(await page.locator('.idea-node').count(), 0);
  assert.equal(await page.locator('.board-heading').count(), 0);
  assert.equal(await page.getByText('A goal kept behind the scenes.', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Rename board', exact: true }).click();
  await page.getByLabel('Board title', { exact: true }).fill('Renamed workspace');
  await page.getByLabel('Board title', { exact: true }).press('Enter');
  await page.getByRole('heading', { name: 'Renamed workspace', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Rename board', exact: true }).click();
  await page.getByLabel('Board title', { exact: true }).fill('Should not save');
  await page.getByLabel('Board title', { exact: true }).press('Escape');
  assert.equal(await page.getByRole('heading', { name: 'Renamed workspace', exact: true }).count(), 1);
  await page.reload(); await page.locator('.graph-area').waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Renamed workspace', exact: true }).count(), 1);
  await page.getByLabel('Your seed idea', { exact: true }).fill('A saved thought');
  await page.getByRole('button', { name: 'Add seed idea', exact: true }).click();
  await page.locator('.idea-node').waitFor();
  await create('Second workspace');
  await page.getByRole('button', { name: 'Delete workspace: Renamed workspace', exact: true }).click();
  await warning.getByText('Renamed workspace', { exact: true }).waitFor();
  assert((await warning.innerText()).includes('its 1 idea'));
  await warning.getByRole('button', { name: 'Cancel', exact: true }).click();
  await warning.waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.board-link').count(), 2);
  await page.getByRole('button', { name: 'Delete workspace: Renamed workspace', exact: true }).click();
  await warning.getByRole('button', { name: 'Delete workspace', exact: true }).click();
  await warning.waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.board-link').count(), 1);
  assert.equal(await page.getByRole('heading', { name: 'Second workspace', exact: true }).count(), 1);
  assert.equal(await page.locator('.idea-node').count(), 0);
  await create('Third workspace');
  await page.getByLabel('Your seed idea', { exact: true }).fill('Remove this with its workspace');
  await page.getByRole('button', { name: 'Add seed idea', exact: true }).click();
  await page.getByRole('button', { name: 'Delete workspace: Third workspace', exact: true }).click();
  await warning.getByRole('button', { name: 'Delete workspace', exact: true }).click();
  await warning.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('heading', { name: 'Second workspace', exact: true }).count(), 1);
  assert.equal(await page.locator('.idea-node').count(), 0);
  await page.getByRole('button', { name: 'Delete workspace: Second workspace', exact: true }).click();
  await page.keyboard.press('Escape'); await warning.waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.board-link').count(), 1);
  await page.getByRole('button', { name: 'Delete workspace: Second workspace', exact: true }).click();
  await warning.waitFor();
  await page.screenshot({ path: 'screenshots/delete-workspace.png', fullPage: true });
  await warning.getByRole('button', { name: 'Delete workspace', exact: true }).click();
  await warning.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Create your first workspace', exact: true }).waitFor();
  await page.reload();
  await page.waitForFunction(() => localStorage.getItem('idea-garden-boards') === '[]');
  assert.equal(await page.locator('.board-link').count(), 0);
  assert.equal(await page.locator('.idea-node').count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Toggle idea inspector', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Workspace checks passed: empty startup, create CTA, inline rename/cancel/persistence, hidden description, sidebar deletion warning/cancel/Escape, inactive/active/last workspace deletion, empty reload, mobile layout.');
} finally { await browser.close(); }
