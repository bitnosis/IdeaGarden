import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { seedExample } from './test-fixtures.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1300, height: 1000 } });
await seedExample(page);
const errors = [], calls = []; page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/models', route => route.fulfill({ json: { models: [{ id: 'qwen3:8b', name: 'Local jury' }] } }));
await page.route('**/api/generate', route => {
  const input = route.request().postDataJSON(); calls.push(input);
  return route.fulfill({ json: input.role === 'judge' ? { verdict: { originality: 4, feasibility: 4, impact: 4, reason: 'Separate jury model.', keywords: ['test'] } } : { ideas: [{ title: 'A branch from the default model', description: 'Unchanged default model.' }] } });
});
const settings = page.getByRole('dialog', { name: 'Settings', exact: true });
const idea = page.getByRole('dialog', { name: 'Idea details', exact: true });
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:4340'); await page.locator('.idea-node').first().waitFor();
  await page.getByRole('heading', { name: 'Tiny rituals, real momentum', exact: true }).click();
  await page.getByRole('button', { name: 'Jury model settings', exact: true }).click();
  await expect(settings.getByRole('tab', { name: 'Models', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(settings.getByRole('button', { name: 'Jury model', exact: true })).toBeFocused();
  const modelsPanel = settings.getByRole('tabpanel', { name: 'Models', exact: true });
  assert.equal(await modelsPanel.getByPlaceholder('Enter API key').count(), 0);
  await settings.getByRole('button', { name: 'Jury model', exact: true }).click();
  await settings.getByRole('combobox', { name: 'Search Jury model', exact: true }).fill('ollama:');
  await settings.getByRole('option', { name: /ollama.*Local jury/ }).click();
  await page.screenshot({ path: 'screenshots/jury-model-settings.png', fullPage: true });
  await settings.getByRole('tab', { name: 'Connections', exact: true }).click();
  const connections = settings.getByRole('tabpanel', { name: 'Connections', exact: true });
  assert.equal(await connections.getByPlaceholder('Enter API key').count(), 3);
  assert.equal(await connections.locator('.provider-model-picker').count(), 0);
  await settings.getByRole('button', { name: 'Done', exact: true }).click(); await settings.waitFor({ state: 'hidden' });
  await page.reload(); await page.locator('.idea-node').first().waitFor();
  await page.getByRole('heading', { name: 'Tiny rituals, real momentum', exact: true }).click();
  await page.getByRole('button', { name: 'Ask the jury again', exact: true }).click();
  await page.getByText('Separate jury model.', { exact: true }).waitFor();
  assert.equal(calls[0].provider, 'ollama'); assert.equal(calls[0].model, 'qwen3:8b');
  await page.getByRole('button', { name: 'Branch into 3 ideas', exact: true }).click();
  await expect(page.locator('.idea-node')).toHaveCount(5);
  assert.equal(calls[1].provider, 'openrouter'); assert.equal(calls[1].model, 'anthropic/claude-sonnet-4.5');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await settings.getByLabel('Idea View', { exact: true }).selectOption('modal');
  await settings.getByRole('button', { name: 'Done', exact: true }).click(); await settings.waitFor({ state: 'hidden' });
  await page.getByRole('heading', { name: 'Tiny rituals, real momentum', exact: true }).click(); await idea.waitFor();
  await idea.getByRole('button', { name: 'Jury model settings', exact: true }).click();
  await expect(settings.getByRole('button', { name: 'Jury model', exact: true })).toBeFocused();
  await idea.waitFor({ state: 'hidden' });
  await settings.getByRole('button', { name: 'Jury model', exact: true }).click();
  await settings.getByRole('option', { name: /openrouter.*anthropic\/claude-sonnet-4\.5/ }).click();
  await settings.getByRole('button', { name: 'Done', exact: true }).click(); await settings.waitFor({ state: 'hidden' });
  await idea.waitFor();
  assert.equal(await idea.getByLabel('Title', { exact: true }).inputValue(), 'Tiny rituals, real momentum');
  await idea.getByRole('button', { name: 'Ask the jury again', exact: true }).click();
  await expect.poll(() => calls.length).toBe(3);
  assert.equal(calls[2].provider, 'openrouter');
  await idea.getByRole('button', { name: 'Close idea details', exact: true }).click(); await idea.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await settings.getByRole('tab', { name: 'Settings', exact: true }).press('ArrowLeft');
  await expect(settings.getByRole('tab', { name: 'Models', exact: true })).toHaveAttribute('aria-selected', 'true');
  await settings.getByRole('tab', { name: 'Models', exact: true }).press('ArrowRight');
  await expect(settings.getByRole('tab', { name: 'Settings', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await settings.getByRole('tab', { name: 'Models', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('Jury model checks passed: Models tab, Connections separation, focused jury shortcut from sidebar/modal, persistent scoring override, unchanged branching model, default reset, return to idea modal, tab keyboard navigation, mobile layout.');
} finally { await browser.close(); }
